#!/usr/bin/env bash
# ==============================================================
# Self-hosted Oswald + Roboto (Sensum Construcciones)
# --------------------------------------------------------------
# Downloads the WOFF2 files the site uses from Google Fonts (SIL Open
# Font License) and writes local-fonts.css. Google serves both families
# as variable fonts: one file per family covers every weight used
# (Oswald 600–700, Roboto 400–700). Only the Latin and Latin Extended
# subsets are kept (Spanish and English need just "latin"; "latin-ext"
# is downloaded by browsers only if a page uses one of its characters).
#
#   cd assets/fonts && ./fetch-fonts.sh
#
# Re-run only to update the fonts (then bump the ?v= in the pages).
# ==============================================================
set -euo pipefail
cd "$(dirname "$0")"
UA="Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/129.0.0.0 Safari/537.36"
CSS_URL="https://fonts.googleapis.com/css2?family=Oswald:wght@600;700&family=Roboto:wght@400;500;600;700&display=swap"
TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT
curl -fsS -A "$UA" "$CSS_URL" -o "$TMP"

{
  echo "/* Self-hosted Oswald + Roboto (SIL Open Font License), generated by fetch-fonts.sh"
  echo "   from Google Fonts. Variable fonts: one file per family and subset. */"
} > local-fonts.css

# Each @font-face block is preceded by a "/* subset */" comment.
python3 - "$TMP" <<'PY'
import re, subprocess, sys
css = open(sys.argv[1]).read()
blocks = re.findall(r'/\* ([a-z-]+) \*/\s*@font-face \{(.*?)\}', css, re.S)
seen = {}
ranges = {}
for subset, body in blocks:
    if subset not in ('latin', 'latin-ext'):
        continue
    family = re.search(r"font-family: '([^']+)'", body).group(1)
    weight = int(re.search(r'font-weight: (\d+)', body).group(1))
    url = re.search(r'url\((https://fonts\.gstatic\.com/[^)]+\.woff2)\)', body).group(1)
    unicode = re.search(r'unicode-range: ([^;]+);', body).group(1)
    key = (family, subset)
    name = f"{family.lower()}-{subset}.woff2"
    if key not in seen:
        subprocess.run(['curl', '-fsS', url, '-o', name], check=True)
        seen[key] = {'name': name, 'url': url, 'weights': [], 'unicode': unicode, 'stretch': 'font-stretch' in body}
    if seen[key]['url'] != url:
        sys.exit(f'{family} {subset}: weights use different files; update this script')
    seen[key]['weights'].append(weight)
with open('local-fonts.css', 'a') as out:
    for (family, subset), d in seen.items():
        w = sorted(d['weights'])
        out.write(f"""
/* {family} — {subset} */
@font-face{{
  font-family: "{family}";
  font-style: normal;
  font-weight: {w[0]} {w[-1]};
{'  font-stretch: 100%;' + chr(10) if d['stretch'] else ''}  font-display: swap;
  src: url("{d['name']}") format("woff2");
  unicode-range: {d['unicode']};
}}
""")
        print(f"  {d['name']}  ({family} {w[0]}–{w[-1]}, {subset})")
PY
echo "Done: local-fonts.css + the files above."
