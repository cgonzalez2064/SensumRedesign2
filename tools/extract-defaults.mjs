// Dev tool: regenerates cms/content/defaults.php from the approved copy in
// assets/main.js (the I18N dictionary), for every bilingual key listed in
// cms/content/schema.php. Run after intentionally changing site copy in code:
//   node tools/extract-defaults.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = readFileSync(join(root, 'assets/main.js'), 'utf8');
const m = src.match(/var I18N = (\{[\s\S]*?\n  \});/);
if (!m) throw new Error('I18N object not found in assets/main.js');
const I18N = Function(`return ${m[1]}`)();

const schema = JSON.parse(execFileSync('php', ['-r', `echo json_encode(require '${join(root, 'cms/content/schema.php')}');`]).toString());
const keys = schema.sections.flatMap((s) => s.fields).filter((f) => f.bilingual !== false).map((f) => f.key);

// The editor writes highlights as *word*; the site renders them as <em>word</em>.
const toEditor = (v) => v.replace(/<em>(.*?)<\/em>/g, '*$1*');
const php = (v) => `'${v.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

let out = `<?php\n// GENERATED by tools/extract-defaults.mjs from assets/main.js — do not edit by hand.\n// Approved default copy for every editable bilingual field (cms/content/schema.php).\nreturn [\n`;
for (const lang of ['es', 'en']) {
  out += `    '${lang}' => [\n`;
  for (const k of keys) {
    const v = I18N[lang][k];
    if (typeof v !== 'string') throw new Error(`Missing ${lang} default for ${k}`);
    if (/[<>]/.test(toEditor(v))) throw new Error(`Default for ${k} contains markup`);
    out += `        ${php(k)} => ${php(toEditor(v))},\n`;
  }
  out += '    ],\n';
}
out += '];\n';
writeFileSync(join(root, 'cms/content/defaults.php'), out);
console.log(`Wrote ${keys.length} keys × 2 languages to cms/content/defaults.php`);
